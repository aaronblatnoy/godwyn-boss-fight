def apply_pose(rig, name, *, clear_animation=True):
    """Apply a named snapshot to any compatible armature; return the rig."""
    if rig.type != 'ARMATURE':
        raise TypeError('Expected an armature object')
    values = POSES[name]
    missing = sorted(set(values) - set(rig.pose.bones.keys()))
    if missing:
        raise ValueError('Target rig lacks bones: ' + ', '.join(missing))
    if clear_animation:
        rig.animation_data_clear()
    for bone in rig.pose.bones:
        bone.matrix_basis.identity()
    for bone_name, transform in values.items():
        bone = rig.pose.bones[bone_name]
        bone.rotation_mode = 'QUATERNION'
        bone.rotation_quaternion = transform['rotation_quaternion']
        bone.location = transform['location']
        bone.scale = transform['scale']
    import bpy
    bpy.context.view_layer.update()
    return rig

def windup(rig, **kwargs):
    return apply_pose(rig, 'windup', **kwargs)

def cross(rig, **kwargs):
    return apply_pose(rig, 'cross', **kwargs)

def follow(rig, **kwargs):
    return apply_pose(rig, 'follow', **kwargs)

def main():
    import argparse, sys, bpy
    from pathlib import Path
    from mathutils import Vector
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model', type=Path, required=True)
    parser.add_argument('--pose', choices=tuple(POSES), required=True)
    parser.add_argument('--rig', default='Armature')
    parser.add_argument('--save', type=Path)
    parser.add_argument('--render', type=Path)
    args = parser.parse_args(sys.argv[sys.argv.index('--')+1:] if '--' in sys.argv else [])
    for destination in (args.save, args.render):
        if destination is None:
            continue
        path = destination.resolve()
        if any(part.startswith(('astra_character_', 'astra_model_')) for part in path.parts):
            parser.error('Character/model-track inputs are read-only')
        allowed = path.is_relative_to(Path('/tmp').resolve()) or path.is_relative_to(root/'renders/astra') or (path.parent == root/'models' and path.name.startswith('astra_'))
        if not allowed or path == args.model.resolve():
            parser.error('Output must be a derived Astra path and must not overwrite the input')
        path.parent.mkdir(parents=True, exist_ok=True)
    if args.model.suffix.lower() == '.glb':
        bpy.ops.wm.read_factory_settings(use_empty=True)
        bpy.ops.import_scene.gltf(filepath=str(args.model.resolve()))
    else:
        bpy.ops.wm.open_mainfile(filepath=str(args.model.resolve()))
    scene = bpy.context.scene
    scene.frame_set(FRAMES[args.pose])
    apply_pose(bpy.data.objects[args.rig], args.pose)
    # Static deformation views deliberately omit motion blur and temporal ribbons.
    for obj in list(scene.objects):
        if obj.name.startswith('Astra_v2_blur_'):
            bpy.data.objects.remove(obj, do_unlink=True)
    scene.render.engine = 'BLENDER_EEVEE'
    scene.render.use_motion_blur = False
    scene.render.use_stamp = False
    if args.render:
        if not scene.camera:
            parser.error('Rendering needs a staged model with a camera/lights')
        scene.camera.location = (0, -11, 2.5)
        scene.camera.rotation_euler = (Vector((0, -.2, 2.0))-scene.camera.location).to_track_quat('-Z', 'Y').to_euler()
        scene.camera.data.type = 'ORTHO'
        scene.camera.data.ortho_scale = 5.25
        scene.render.resolution_x = scene.render.resolution_y = 640
        scene.render.resolution_percentage = 100
        scene.render.image_settings.file_format = 'PNG'
        scene.render.filepath = str(args.render.resolve())
        bpy.ops.render.render(write_still=True)
    if args.save:
        bpy.context.preferences.filepaths.save_version = 0
        bpy.ops.wm.save_as_mainfile(filepath=str(args.save.resolve()))

if __name__ == '__main__':
    main()
